 * ДОКУМЕНТАЦИЯ ПО ХУКУ market.vendors.first
 * ============================================================
 *
 * Назначение:
 *   Хук market.vendors.list.first срабатывает в начале страницы витрин
 *   продавцов модуля Market (файл modules/market/inc/market.vendors.php).
 *   Плагин использует его для отключения статического кэширования на тех
 *   страницах, где используются мультикатегории.
 *
 * Что делает:
 *   1. Регистрирует таблицу cot_market_multicats в объекте Cot::$db,
 *      чтобы её можно было использовать через $db->market_multicats.
 *   2. Если категория не выбрана (мы на главной странице витрин) —
 *      проверяет, есть ли в таблице мультикатегорий хотя бы одна запись.
 *      Если есть, принудительно отключает кэш.
 *   3. Если категория выбрана — получает её structure_id и проверяет,
 *      есть ли для неё товары, привязанные через мультикатегории.
 *      Если есть, отключает кэш.
 *
 * Почему нужен:
 *   Статический кэш Cotonti сохраняет готовый HTML страницы. Когда товар
 *   выводится в нескольких категориях одновременно (мультикатегории),
 *   кэш может сохранить неконсистентное состояние и показать «пустой
 *   белый экран» или устаревший список. Принудительное отключение кэша
 *   для таких страниц решает проблему.
