// Стандартная защита от прямого обращения к файлу
defined('COT_CODE') or die('Wrong URL');

// Регистрируем таблицу связей мультикатегорий в объекте Cot::$db,
// чтобы к ней можно было обращаться через Cot::$db->market_multicats
Cot::$db->registerTable('market_multicats');

// Объявляем глобальную переменную $c — код текущей категории из GET-запроса
global $c;

/* =====================================================================
 * СЛУЧАЙ 1: КАТЕГОРИЯ НЕ ВЫБРАНА (ГЛАВНАЯ СТРАНИЦА ВИТРИН)
 * ---------------------------------------------------------------------
 * Проверяем, есть ли в таблице мультикатегорий хотя бы одна запись.
 * Если есть — отключаем кэш, чтобы избежать сохранения некорректного
 * состояния главной страницы после перехода из категории.
 * ===================================================================== */

// Если категория не задана
if (empty($c)) {

    // Проверяем, есть ли хотя бы одна связь мультикатегорий в таблице
    $has_any_multi = (bool) Cot::$db->query(
        "SELECT 1 FROM " . Cot::$db->market_multicats . " LIMIT 1"
    )->fetchColumn();

    // Если мультикатегории используются хотя бы для одного товара —
    // принудительно отключаем кэширование
    if ($has_any_multi) {
        Cot::$cache = false;
    }

    // Дальнейшая обработка не требуется — выходим из хука
    return;
}

/* =====================================================================
 * СЛУЧАЙ 2: КАТЕГОРИЯ ВЫБРАНА
 * ---------------------------------------------------------------------
 * Получаем structure_id текущей категории и проверяем, есть ли для неё
 * товары, привязанные через мультикатегории. Если есть — отключаем кэш.
 * ===================================================================== */

// Получаем экземпляр объекта базы данных Cotonti для удобства
$db = Cot::$db;

// Определяем числовой ID структуры (раздела) по коду текущей категории.
// Используем безопасное экранирование значения категории и ограничиваем
// выборку областью 'market'. fetchColumn() возвращает первый столбец.
$cat_id = (int) $db->query(
    "SELECT structure_id FROM {$db->structure}
     WHERE structure_code = " . $db->quote($c) . "
       AND structure_area = 'market'"
)->fetchColumn();

// Если structure_id найден (больше нуля) — продолжаем проверку
if ($cat_id > 0) {

    // Проверяем, существует ли хотя бы одна связь мультикатегорий
    // для данной категории
    $has_multi = (bool) $db->query(
        "SELECT 1 FROM " . $db->market_multicats . "
         WHERE pcat_cat_id = {$cat_id} LIMIT 1"
    )->fetchColumn();

    // Если категория содержит товары с мультикатегориями — отключаем кэш,
    // чтобы страница всегда генерировалась динамически
    if ($has_multi) {
        Cot::$cache = false;
    }
}